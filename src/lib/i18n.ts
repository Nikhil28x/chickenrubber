const MESSAGES: Record<Lang, Messages> = { en, hi, kn, te, ta, ml, bn };

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const messages = MESSAGES[lang] ?? en;
  return (key, values) => {
    const text = messages[key] ?? en[key];
    return values
      ? text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match))
      : text;
  };
}

// The page shares the chosen language with the components inside it.
const KEY = Symbol('i18n');

export function setI18n(getLang: () => Lang) {
  setContext(KEY, getLang);
}

/** Returns a translate function that follows the page's current language. */
export function useI18n(): Translate {
  const getLang = getContext<(() => Lang) | undefined>(KEY);
  return (key, values) => translator(getLang?.() ?? 'en')(key, values);
}
